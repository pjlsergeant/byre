// Package iconletters draws a deliver app's ICON LETTERS (GLOSSARY): up
// to two letters or digits, uppercased, over the install's icon art, so
// labeled installs that would otherwise share one picture are told apart
// at Dock size. The font is Go Bold (golang.org/x/image/font/gofont),
// embedded, so rendering needs nothing from the host.
package iconletters

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"hash/crc32"
	"image"
	"image/color"
	"image/draw"
	"image/png"
	"strings"
	"sync"
	"unicode"
	"unicode/utf8"

	"golang.org/x/image/font"
	"golang.org/x/image/font/gofont/gobold"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/font/sfnt"
	"golang.org/x/image/math/fixed"
)

// Size-relative drawing constants, as fractions of the icon's side.
const (
	capHeightFrac = 0.325    // cap height of the letters
	maxWidthFrac  = 0.84     // widest the ink may run before the size shrinks
	outlineFrac   = 1.0 / 48 // outline stamp distance
	washAlpha     = 128      // black wash over the art, masked by its alpha
)

// markerText is the tEXt Comment a rendered icon carries: how a later
// install recognizes an icon file as its own to replace.
const markerText = "Generated by byre."

const markerKeyword = "Comment"

// iconSides are the square sizes a byre-rendered icon can have: the
// sizes packICNS (internal/commands/installapp.go) gives an icns type
// to, so the only sizes an install accepts as base art and thus the only
// sizes Render ever writes. Change the two together.
var iconSides = map[int]bool{128: true, 256: true, 512: true, 1024: true}

var (
	fontOnce sync.Once
	goBold   *sfnt.Font
	fontErr  error
)

func loadFont() (*sfnt.Font, error) {
	fontOnce.Do(func() {
		goBold, fontErr = opentype.Parse(gobold.TTF)
	})
	return goBold, fontErr
}

// usable maps one rune to the form drawn: letters and digits, uppercased,
// that the icon font has a glyph for.
func usable(r rune) (rune, bool) {
	if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
		return 0, false
	}
	f, err := loadFont()
	if err != nil {
		return 0, false
	}
	u := unicode.ToUpper(r)
	var buf sfnt.Buffer
	gi, err := f.GlyphIndex(&buf, u)
	if err != nil || gi == 0 {
		return 0, false
	}
	return u, true
}

// Normalize validates a --icon-letters value and returns the form drawn:
// one or two letters or digits, uppercased.
func Normalize(s string) (string, error) {
	if !utf8.ValidString(s) {
		return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
	}
	n := utf8.RuneCountInString(s)
	if n < 1 || n > 2 {
		return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
	}
	var b strings.Builder
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
		}
		u, ok := usable(r)
		if !ok {
			return "", fmt.Errorf("--icon-letters: %q has no glyph in the icon font", string(r))
		}
		b.WriteRune(u)
	}
	return b.String(), nil
}

// FromLabel derives letters from a label: the first two runes usable by
// Normalize's per-rune rule, uppercased; "" when none.
func FromLabel(s string) string {
	var b strings.Builder
	n := 0
	for _, r := range s {
		if u, ok := usable(r); ok {
			b.WriteRune(u)
			n++
			if n == 2 {
				break
			}
		}
	}
	return b.String()
}

// Render draws letters (normalized by Render itself) over a square PNG and
// returns a PNG of the same size carrying the byre marker chunk. The bytes
// are deterministic on one architecture but may differ across them (the
// float rasterizer's arithmetic can compile to fused multiply-add), so
// never golden-pin rendered bytes; assert properties of the image.
func Render(basePNG []byte, letters string) ([]byte, error) {
	letters, err := Normalize(letters)
	if err != nil {
		return nil, err
	}
	base, format, err := image.Decode(bytes.NewReader(basePNG))
	if err != nil || format != "png" {
		return nil, fmt.Errorf("icon must be a PNG: %v", err)
	}
	b := base.Bounds()
	if b.Dx() != b.Dy() || b.Dx() == 0 {
		return nil, fmt.Errorf("icon must be square (got %dx%d)", b.Dx(), b.Dy())
	}
	f, err := loadFont()
	if err != nil {
		return nil, fmt.Errorf("icon font: %v", err)
	}
	side := b.Dx()
	dst := image.NewNRGBA(image.Rect(0, 0, side, side))
	draw.Draw(dst, dst.Bounds(), base, b.Min, draw.Src)
	// The wash darkens colour and leaves alpha exactly as the art had it:
	// transparent corners stay transparent, and the art stays faintly
	// visible beneath the letters.
	for i := 0; i < len(dst.Pix); i += 4 {
		for c := 0; c < 3; c++ {
			dst.Pix[i+c] = uint8(uint32(dst.Pix[i+c]) * (255 - washAlpha) / 255)
		}
	}

	face, err := sizedFace(f, letters, float64(side))
	if err != nil {
		return nil, err
	}
	defer face.Close()
	bounds, _ := font.BoundString(face, letters)
	inkW := bounds.Max.X - bounds.Min.X
	inkH := bounds.Max.Y - bounds.Min.Y
	// Centre the ink, not the advance: a "1" or a "W" sits where the eye
	// expects it.
	half := fixed.I(side) / 2
	dotX := half - inkW/2 - bounds.Min.X
	dotY := half - inkH/2 - bounds.Min.Y
	d := fixed.Int26_6(float64(side) * outlineFrac * 64)
	drawer := &font.Drawer{Dst: dst, Face: face}
	drawer.Src = image.NewUniform(color.NRGBA{0, 0, 0, 255})
	for _, off := range [][2]fixed.Int26_6{{-d, -d}, {0, -d}, {d, -d}, {-d, 0}, {d, 0}, {-d, d}, {0, d}, {d, d}} {
		drawer.Dot = fixed.Point26_6{X: dotX + off[0], Y: dotY + off[1]}
		drawer.DrawString(letters)
	}
	drawer.Src = image.NewUniform(color.NRGBA{255, 255, 255, 255})
	drawer.Dot = fixed.Point26_6{X: dotX, Y: dotY}
	drawer.DrawString(letters)

	var out bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.DefaultCompression}
	if err := enc.Encode(&out, dst); err != nil {
		return nil, err
	}
	return insertMarker(out.Bytes()), nil
}

// sizedFace picks the face whose cap height is capHeightFrac of the side,
// shrunk so the ink fits maxWidthFrac of it.
func sizedFace(f *sfnt.Font, letters string, side float64) (font.Face, error) {
	const probe = 100.0
	pf, err := opentype.NewFace(f, &opentype.FaceOptions{Size: probe, DPI: 72, Hinting: font.HintingNone})
	if err != nil {
		return nil, err
	}
	capH := float64(pf.Metrics().CapHeight) / 64
	if capH <= 0 {
		capH = 0.7 * probe
	}
	pb, _ := font.BoundString(pf, letters)
	inkW := float64(pb.Max.X-pb.Min.X) / 64
	pf.Close()
	size := probe * capHeightFrac * side / capH
	if w := inkW * size / probe; w > maxWidthFrac*side {
		size *= maxWidthFrac * side / w
	}
	return opentype.NewFace(f, &opentype.FaceOptions{Size: size, DPI: 72, Hinting: font.HintingNone})
}

var pngSig = []byte("\x89PNG\r\n\x1a\n")

// insertMarker adds the marker tEXt chunk right after IHDR (Go's encoder
// always writes IHDR first, 13 data bytes). Decoders skip ancillary chunks.
func insertMarker(p []byte) []byte {
	const ihdrEnd = 8 + 4 + 4 + 13 + 4
	data := append([]byte(markerKeyword+"\x00"), markerText...)
	var chunk bytes.Buffer
	_ = binary.Write(&chunk, binary.BigEndian, uint32(len(data)))
	chunk.WriteString("tEXt")
	chunk.Write(data)
	crc := crc32.NewIEEE()
	crc.Write([]byte("tEXt"))
	crc.Write(data)
	_ = binary.Write(&chunk, binary.BigEndian, crc.Sum32())
	out := make([]byte, 0, len(p)+chunk.Len())
	out = append(out, p[:ihdrEnd]...)
	out = append(out, chunk.Bytes()...)
	return append(out, p[ihdrEnd:]...)
}

// IsByreRendered reports a well-formed PNG whose marker tEXt chunk sits
// immediately after IHDR, where insertMarker puts it: every chunk's CRC
// valid, the walk ending exactly at IEND, the header declaring a square
// at one of iconSides, and the whole image decodable (png.Decode enforces
// what the walk does not: critical-chunk order, IDAT present, a
// zero-length IEND). The size bound runs before the decode because the
// file is untrusted and png.Decode allocates the declared dimensions up
// front: a few hundred bytes declaring 100000x100000 would ask for ~40GB.
// Anything looser would let a foreign file that merely mentions the marker
// be claimed, and overwritten, as byre's own.
func IsByreRendered(p []byte) bool {
	if !bytes.HasPrefix(p, pngSig) {
		return false
	}
	want := append([]byte(markerKeyword+"\x00"), markerText...)
	rest := p[len(pngSig):]
	for i := 0; ; i++ {
		if len(rest) < 12 {
			return false
		}
		n := uint64(binary.BigEndian.Uint32(rest[:4]))
		if n > uint64(len(rest)-12) {
			return false
		}
		size := int(n) // fits: bounded by len(rest)
		typ := string(rest[4:8])
		data := rest[8 : 8+size]
		if crc32.ChecksumIEEE(rest[4:8+size]) != binary.BigEndian.Uint32(rest[8+size:12+size]) {
			return false
		}
		switch {
		case i == 0 && (typ != "IHDR" || size != 13):
			return false
		case i == 1 && (typ != "tEXt" || !bytes.Equal(data, want)):
			return false
		}
		rest = rest[12+size:]
		if typ == "IEND" {
			if len(rest) != 0 {
				return false
			}
			break
		}
	}
	cfg, err := png.DecodeConfig(bytes.NewReader(p))
	if err != nil || cfg.Width != cfg.Height || !iconSides[cfg.Width] {
		return false
	}
	_, err = png.Decode(bytes.NewReader(p))
	return err == nil
}
