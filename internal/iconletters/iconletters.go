// Package iconletters draws a deliver app's ICON LETTERS (GLOSSARY): up
// to two letters or digits, uppercased, over the install's icon art, so
// labeled installs that would otherwise share one picture are told apart
// at Dock size. The font is Go Bold (golang.org/x/image/font/gofont),
// embedded, so rendering needs nothing from the host.
package iconletters

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"hash/crc32"
	"image"
	"image/color"
	"image/png"
	"math"
	"strings"
	"sync"
	"unicode"
	"unicode/utf8"

	"golang.org/x/image/draw"
	"golang.org/x/image/font"
	"golang.org/x/image/font/gofont/gobold"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/font/sfnt"
	"golang.org/x/image/math/fixed"
)

// Size-relative drawing constants, as fractions of the icon's side.
const (
	capHeightFrac = 0.325    // cap height of the letters at snapBelow and up
	smallCapFrac  = 0.42     // cap height at the smallest side, Sides[0]
	maxWidthFrac  = 0.84     // widest the ink may run before the size shrinks
	outlineFrac   = 1.0 / 48 // outline stamp distance
	minOutlinePx  = 2        // outline floor once the side can afford it
	snapBelow     = 128      // below this side, geometry lands on whole pixels
)

// markerText is the tEXt Comment a rendered icon carries: how a later
// install recognizes an icon file as its own to replace.
const markerText = "Generated by byre."

const markerKeyword = "Comment"

// Sides are the square sizes a byre-rendered icon can have: the union of
// the icns renditions and the Linux hicolor sizes the install writes
// (internal/commands/installapp.go), so the only sizes Render draws and
// the only sizes IsByreRendered accepts. Ascending.
var Sides = []int{16, 24, 32, 48, 64, 128, 256, 512, 1024}

var iconSides = func() map[int]bool {
	m := make(map[int]bool, len(Sides))
	for _, s := range Sides {
		m[s] = true
	}
	return m
}()

var (
	fontOnce sync.Once
	goBold   *sfnt.Font
	fontErr  error
)

func loadFont() (*sfnt.Font, error) {
	fontOnce.Do(func() {
		goBold, fontErr = opentype.Parse(gobold.TTF)
	})
	return goBold, fontErr
}

// usable maps one rune to the form drawn: letters and digits, uppercased,
// that the icon font has a glyph for.
func usable(r rune) (rune, bool) {
	if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
		return 0, false
	}
	f, err := loadFont()
	if err != nil {
		return 0, false
	}
	u := unicode.ToUpper(r)
	var buf sfnt.Buffer
	gi, err := f.GlyphIndex(&buf, u)
	if err != nil || gi == 0 {
		return 0, false
	}
	return u, true
}

// Normalize validates a --icon-letters value and returns the form drawn:
// one or two letters or digits, uppercased.
func Normalize(s string) (string, error) {
	if !utf8.ValidString(s) {
		return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
	}
	n := utf8.RuneCountInString(s)
	if n < 1 || n > 2 {
		return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
	}
	var b strings.Builder
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return "", fmt.Errorf("--icon-letters: takes one or two letters or digits (got %q)", s)
		}
		u, ok := usable(r)
		if !ok {
			return "", fmt.Errorf("--icon-letters: %q has no glyph in the icon font", string(r))
		}
		b.WriteRune(u)
	}
	return b.String(), nil
}

// FromLabel derives letters from a label: the first two runes usable by
// Normalize's per-rune rule, uppercased; "" when none.
func FromLabel(s string) string {
	var b strings.Builder
	n := 0
	for _, r := range s {
		if u, ok := usable(r); ok {
			b.WriteRune(u)
			n++
			if n == 2 {
				break
			}
		}
	}
	return b.String()
}

// Render draws letters ("" = the plain art; otherwise normalized by
// Render itself) over a square PNG scaled to side, and returns a side x
// side PNG carrying the byre marker chunk. side must be one of Sides and
// no larger than the art: the letters are drawn afresh at each size, the
// art only ever scaled down. The bytes are deterministic on one
// architecture but may differ across them (the float rasterizer's and
// scaler's arithmetic can compile to fused multiply-add), so never
// golden-pin rendered bytes; assert properties of the image.
func Render(basePNG []byte, letters string, side int) ([]byte, error) {
	set, err := RenderSizes(basePNG, letters, []int{side})
	if err != nil {
		return nil, err
	}
	return set[side], nil
}

// RenderSizes is Render at every one of sides, decoding the art once and
// drawing the sizes in parallel. The result is keyed by side.
func RenderSizes(basePNG []byte, letters string, sides []int) (map[int][]byte, error) {
	if letters != "" {
		n, err := Normalize(letters)
		if err != nil {
			return nil, err
		}
		letters = n
	}
	for _, side := range sides {
		if !iconSides[side] {
			return nil, fmt.Errorf("cannot render a %d px icon: sizes are %v", side, Sides)
		}
	}
	base, err := decodeBase(basePNG)
	if err != nil {
		return nil, err
	}
	for _, side := range sides {
		if side > base.Bounds().Dx() {
			return nil, fmt.Errorf("icon art is %d px; cannot render %d px without upscaling it", base.Bounds().Dx(), side)
		}
	}
	var f *sfnt.Font
	if letters != "" {
		if f, err = loadFont(); err != nil {
			return nil, fmt.Errorf("icon font: %v", err)
		}
	}
	outs := make([][]byte, len(sides))
	errs := make([]error, len(sides))
	var wg sync.WaitGroup
	for i, side := range sides {
		wg.Add(1)
		go func() {
			defer wg.Done()
			outs[i], errs[i] = renderOne(base, f, letters, side)
		}()
	}
	wg.Wait()
	set := make(map[int][]byte, len(sides))
	for i, side := range sides {
		if errs[i] != nil {
			return nil, errs[i]
		}
		set[side] = outs[i]
	}
	return set, nil
}

// decodeBase decodes the art as a square image converted to RGBA, the
// form the scaler has a fast path for (the ssh art is paletted).
func decodeBase(basePNG []byte) (*image.RGBA, error) {
	base, format, err := image.Decode(bytes.NewReader(basePNG))
	if err != nil || format != "png" {
		return nil, fmt.Errorf("icon must be a PNG: %v", err)
	}
	b := base.Bounds()
	if b.Dx() != b.Dy() || b.Dx() == 0 {
		return nil, fmt.Errorf("icon must be square (got %dx%d)", b.Dx(), b.Dy())
	}
	rgba := image.NewRGBA(image.Rect(0, 0, b.Dx(), b.Dy()))
	draw.Draw(rgba, rgba.Bounds(), base, b.Min, draw.Src)
	return rgba, nil
}

// scaleArt returns the art at side x side: a copy at its own size,
// CatmullRom-downscaled otherwise.
func scaleArt(src *image.RGBA, side int) *image.RGBA {
	dst := image.NewRGBA(image.Rect(0, 0, side, side))
	if side == src.Bounds().Dx() {
		copy(dst.Pix, src.Pix)
		return dst
	}
	draw.CatmullRom.Scale(dst, dst.Bounds(), src, src.Bounds(), draw.Src, nil)
	return dst
}

// geometry is the letter layout at one side: the cap height and outline
// stamp distance in pixels, and whether positions snap to whole pixels.
// The rasterizer does no hinting, so below snapBelow the cap height,
// outline and pen positions are rounded to whole pixels instead: edges
// that land on the pixel grid stay sharp instead of smearing across two
// half-lit rows. Small icons also get proportionally taller letters,
// rising linearly from capHeightFrac at snapBelow to smallCapFrac at the
// smallest side, because at 16-32 px a third of the side is too few
// pixels to read.
func geometry(side int) (capPx, outlinePx float64, snap bool) {
	s := float64(side)
	if side >= snapBelow {
		return capHeightFrac * s, max(s*outlineFrac, minOutlinePx), false
	}
	lo := float64(Sides[0])
	t := (s - lo) / (snapBelow - lo)
	frac := smallCapFrac + (capHeightFrac-smallCapFrac)*t
	capPx = math.Round(frac * s)
	outlinePx = math.Round(max(s*outlineFrac, min(minOutlinePx, s/16)))
	return capPx, outlinePx, true
}

// renderOne draws one size: the scaled art, then the letters (8-stamp
// black outline, white fill), encoded with the marker.
func renderOne(base *image.RGBA, f *sfnt.Font, letters string, side int) ([]byte, error) {
	dst := scaleArt(base, side)
	if letters != "" {
		if err := drawLetters(dst, f, letters, side); err != nil {
			return nil, err
		}
	}
	var out bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.DefaultCompression}
	if err := enc.Encode(&out, dst); err != nil {
		return nil, err
	}
	return insertMarker(out.Bytes()), nil
}

// drawLetters draws letters centred on dst: an 8-stamp black outline,
// then the white fill. Glyphs are placed one at a time so that, when the
// geometry snaps, every glyph's ink left edge (a stem, in most letters)
// and the shared baseline land on whole pixels.
func drawLetters(dst *image.RGBA, f *sfnt.Font, letters string, side int) error {
	capPx, outlinePx, snap := geometry(side)
	face, err := sizedFace(f, letters, float64(side), capPx, snap)
	if err != nil {
		return err
	}
	defer face.Close()

	// Pen x of each glyph, relative to the first glyph's ink left edge.
	type glyph struct {
		r rune
		x fixed.Int26_6
	}
	var glyphs []glyph
	ink := fixed.Rectangle26_6{Min: fixed.Point26_6{X: 1 << 30, Y: 1 << 30}, Max: fixed.Point26_6{X: -1 << 30, Y: -1 << 30}}
	var pen, origin fixed.Int26_6
	prev := rune(-1)
	for i, r := range []rune(letters) {
		if prev >= 0 {
			pen += face.Kern(prev, r)
		}
		gb, adv, _ := face.GlyphBounds(r)
		if i == 0 {
			origin = gb.Min.X
		}
		x := pen - origin
		if snap {
			x = fixed.I((x + gb.Min.X).Round()) - gb.Min.X
		}
		glyphs = append(glyphs, glyph{r, x})
		ink.Min.X, ink.Max.X = min(ink.Min.X, x+gb.Min.X), max(ink.Max.X, x+gb.Max.X)
		ink.Min.Y, ink.Max.Y = min(ink.Min.Y, gb.Min.Y), max(ink.Max.Y, gb.Max.Y)
		pen += adv
		prev = r
	}
	// Centre the ink, not the advance: a "1" or a "W" sits where the eye
	// expects it.
	half := fixed.I(side) / 2
	dotX := half - (ink.Max.X-ink.Min.X)/2 - ink.Min.X
	dotY := half - (ink.Max.Y-ink.Min.Y)/2 - ink.Min.Y
	d := fixed.Int26_6(outlinePx * 64)
	if snap {
		dotX = fixed.I(dotX.Round())
		dotY = fixed.I(dotY.Round())
		d = fixed.I(int(outlinePx))
	}
	drawer := &font.Drawer{Dst: dst, Face: face}
	draw := func(dx, dy fixed.Int26_6) {
		for _, g := range glyphs {
			drawer.Dot = fixed.Point26_6{X: dotX + g.x + dx, Y: dotY + dy}
			drawer.DrawString(string(g.r))
		}
	}
	drawer.Src = image.NewUniform(color.RGBA{0, 0, 0, 255})
	for _, off := range [][2]fixed.Int26_6{{-d, -d}, {0, -d}, {d, -d}, {-d, 0}, {d, 0}, {-d, d}, {0, d}, {d, d}} {
		draw(off[0], off[1])
	}
	drawer.Src = image.NewUniform(color.RGBA{255, 255, 255, 255})
	draw(0, 0)
	return nil
}

// sizedFace picks the face whose cap height is capPx, shrunk so the ink
// fits maxWidthFrac of the side; with snap, a shrunk cap height is
// rounded down to whole pixels too.
func sizedFace(f *sfnt.Font, letters string, side, capPx float64, snap bool) (font.Face, error) {
	const probe = 100.0
	pf, err := opentype.NewFace(f, &opentype.FaceOptions{Size: probe, DPI: 72, Hinting: font.HintingNone})
	if err != nil {
		return nil, err
	}
	capH := float64(pf.Metrics().CapHeight) / 64
	if capH <= 0 {
		capH = 0.7 * probe
	}
	pb, _ := font.BoundString(pf, letters)
	inkW := float64(pb.Max.X-pb.Min.X) / 64
	pf.Close()
	size := probe * capPx / capH
	if w := inkW * size / probe; w > maxWidthFrac*side {
		size *= maxWidthFrac * side / w
		if snap {
			size = probe * max(1, math.Floor(size*capH/probe)) / capH
		}
	}
	return opentype.NewFace(f, &opentype.FaceOptions{Size: size, DPI: 72, Hinting: font.HintingNone})
}

var pngSig = []byte("\x89PNG\r\n\x1a\n")

// insertMarker adds the marker tEXt chunk right after IHDR (Go's encoder
// always writes IHDR first, 13 data bytes). Decoders skip ancillary chunks.
func insertMarker(p []byte) []byte {
	const ihdrEnd = 8 + 4 + 4 + 13 + 4
	data := append([]byte(markerKeyword+"\x00"), markerText...)
	var chunk bytes.Buffer
	_ = binary.Write(&chunk, binary.BigEndian, uint32(len(data)))
	chunk.WriteString("tEXt")
	chunk.Write(data)
	crc := crc32.NewIEEE()
	crc.Write([]byte("tEXt"))
	crc.Write(data)
	_ = binary.Write(&chunk, binary.BigEndian, crc.Sum32())
	out := make([]byte, 0, len(p)+chunk.Len())
	out = append(out, p[:ihdrEnd]...)
	out = append(out, chunk.Bytes()...)
	return append(out, p[ihdrEnd:]...)
}

// IsByreRendered reports a well-formed PNG whose marker tEXt chunk sits
// immediately after IHDR, where insertMarker puts it: every chunk's CRC
// valid, the walk ending exactly at IEND, the header declaring a square
// at one of iconSides, and the whole image decodable (png.Decode enforces
// what the walk does not: critical-chunk order, IDAT present, a
// zero-length IEND). The size bound runs before the decode because the
// file is untrusted and png.Decode allocates the declared dimensions up
// front: a few hundred bytes declaring 100000x100000 would ask for ~40GB.
// Anything looser would let a foreign file that merely mentions the marker
// be claimed, and overwritten, as byre's own.
func IsByreRendered(p []byte) bool {
	if !bytes.HasPrefix(p, pngSig) {
		return false
	}
	want := append([]byte(markerKeyword+"\x00"), markerText...)
	rest := p[len(pngSig):]
	for i := 0; ; i++ {
		if len(rest) < 12 {
			return false
		}
		n := uint64(binary.BigEndian.Uint32(rest[:4]))
		if n > uint64(len(rest)-12) {
			return false
		}
		size := int(n) // fits: bounded by len(rest)
		typ := string(rest[4:8])
		data := rest[8 : 8+size]
		if crc32.ChecksumIEEE(rest[4:8+size]) != binary.BigEndian.Uint32(rest[8+size:12+size]) {
			return false
		}
		switch {
		case i == 0 && (typ != "IHDR" || size != 13):
			return false
		case i == 1 && (typ != "tEXt" || !bytes.Equal(data, want)):
			return false
		}
		rest = rest[12+size:]
		if typ == "IEND" {
			if len(rest) != 0 {
				return false
			}
			break
		}
	}
	cfg, err := png.DecodeConfig(bytes.NewReader(p))
	if err != nil || cfg.Width != cfg.Height || !iconSides[cfg.Width] {
		return false
	}
	_, err = png.Decode(bytes.NewReader(p))
	return err == nil
}
